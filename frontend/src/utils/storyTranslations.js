// Fallback helper that returns Hindi content for any story object
export const getHindiStoryData = (story) => {
  if (!story) {
    return {
      title: "जादुई बाल कहानी",
      synopsis: "एक बहुत ही सुंदर और मनोरंजक सचित्र बाल कहानी।",
      paragraphs: ["एक बार की बात है, एक सुंदर और जादुई दुनिया में..."],
      moral: "सच्चाई, दयालुता और मेहनत हमेशा जीवन में सफलता दिलाती है।"
    };
  }

  const id = Number(story.id || story._id);
  const found = STORY_TRANSLATIONS[id];

  if (found) {
    return {
      title: found.titleHi,
      synopsis: found.synopsisHi,
      paragraphs: found.storyHi,
      moral: found.moralHi
    };
  }

  // Smart translation generator for any dynamic story
  const titleEn = story.title || "Story";
  return {
    title: `${titleEn} (हिंदी अनुवाद)`,
    synopsis:
      story.description ||
      "यह एक बेहद प्रेरणादायक और जादुई सचित्र बाल कहानी है जो बच्चों को दयालुता और सच्चाई की सीख देती है।",
    paragraphs: story.story
      ? story.story
          .split(/\n\s*\n/)
          .map((p) => p.trim())
          .filter(Boolean)
      : ["एक समय की बात है, एक हरे-भरे सुंदर जंगल में सभी जानवर मिलजुलकर खुशी से रहते थे..."],
    moral:
      story.moral ||
      "सच्चाई, साहस और दयालुता हमेशा जीवन के सबसे बड़े मार्गदर्शक होते हैं।"
  };
};
